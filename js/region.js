export const REGION = CONFIGS[document.documentElement.dataset.region] || CONFIGS.tokyo;
// 地図に置く区名: 政令市の区は市の名前を省く（例: 大阪市淀川区 -> 淀川区）。よみも市の部分を省く
export function mapLabelNames(munis) {
  const out = munis.map(m => [m.n, m.y || '']);
  if (!REGION.shortWards) return out;
  const groups = {};
  munis.forEach((m, i) => { const r = /^(.+?市)(.+区)$/.exec(m.n); if (r) (groups[r[1]] ||= []).push([i, r[2]]); });
  for (const g of Object.values(groups)) {
    if (g.length < 2) continue;
    let pre = munis[g[0][0]].y || '';
    for (const [i] of g) { const y = munis[i].y || ''; let k = 0; while (k < pre.length && pre[k] === y[k]) k++; pre = pre.slice(0, k); }
    pre = pre.slice(0, pre.lastIndexOf('し') + 1);   // 「おおさかし」「さかいし」まで
    for (const [i, ward] of g) out[i] = [ward, pre && (munis[i].y || '').startsWith(pre) ? munis[i].y.slice(pre.length) : (munis[i].y || '')];
  }
  return out;
}
// 経緯度 -> 地図の座標（1単位 = 100m）
export function lonlatToXZ(lon, lat) {
  const p = REGION.proj; return [(lon - p.lon0) * p.mlon / 100, -(lat - p.lat0) * p.mlat / 100];
}
